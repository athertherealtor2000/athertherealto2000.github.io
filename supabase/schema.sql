alter table public.products enable row level security;
alter table public.profiles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.inventory_movements enable row level security;
alter table public.breeding_batches enable row level security;

-- Public visitors can view active categories and active products.
drop policy if exists "Anyone can view active categories" on public.categories;
create policy "Anyone can view active categories"
on public.categories for select to anon, authenticated
using (is_active = true);

drop policy if exists "Anyone can view active products" on public.products;
create policy "Anyone can view active products"
on public.products for select to anon, authenticated
using (is_active = true);

-- Customers can view and update only their own profile.
drop policy if exists "Customers can view own profile" on public.profiles;
create policy "Customers can view own profile"
on public.profiles for select to authenticated
using (auth.uid() = id);

drop policy if exists "Customers can update own profile" on public.profiles;
create policy "Customers can update own profile"
on public.profiles for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

-- Customers can create orders and view only their own orders.
drop policy if exists "Customers can view own orders" on public.orders;
create policy "Customers can view own orders"
on public.orders for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Customers can create own orders" on public.orders;
create policy "Customers can create own orders"
on public.orders for insert to authenticated
with check (auth.uid() = user_id);

-- Order lines are visible/insertable only when the parent order belongs to the customer.
drop policy if exists "Customers can view own order items" on public.order_items;
create policy "Customers can view own order items"
on public.order_items for select to authenticated
using (exists (
  select 1 from public.orders o
  where o.id = order_items.order_id and o.user_id = auth.uid()
));

drop policy if exists "Customers can add items to own orders" on public.order_items;
create policy "Customers can add items to own orders"
on public.order_items for insert to authenticated
with check (exists (
  select 1 from public.orders o
  where o.id = order_items.order_id and o.user_id = auth.uid()
));

-- No anon/authenticated policies are created for inventory_movements or
-- breeding_batches. They remain private to trusted server/service-role operations.
