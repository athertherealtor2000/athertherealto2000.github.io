-- Our Aquarium World: initial Supabase database schema
-- Run this entire file once in Supabase Dashboard > SQL Editor > New query.
-- This creates the tables and security policies; it does not insert sample products.

create extension if not exists pgcrypto;

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories(id) on delete set null,
  name text not null,
  slug text not null unique,
  description text,
  price numeric(12,2) check (price is null or price >= 0),
  currency char(3) not null default 'AED',
  image_url text,
  is_active boolean not null default false,
  is_wholesale_only boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  country text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete restrict,
  order_number bigint generated by default as identity unique,
  status text not null default 'pending'
    check (status in ('pending','confirmed','processing','shipped','completed','cancelled')),
  currency char(3) not null default 'AED',
  customer_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.inventory (
  product_id uuid primary key references public.products(id) on delete cascade,
  quantity_on_hand integer not null default 0 check (quantity_on_hand >= 0),
  unit text not null default 'pcs',
  updated_at timestamptz not null default now()
);

create table if not exists public.breeding_batches (
  id uuid primary key default gen_random_uuid(),
  product_id uuid references public.products(id) on delete set null,
  batch_name text not null,
  species_or_variant text,
  start_date date,
  starting_count integer check (starting_count is null or starting_count >= 0),
  current_count integer check (current_count is null or current_count >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists orders_customer_id_idx on public.orders(customer_id);
create index if not exists order_items_order_id_idx on public.order_items(order_id);
create index if not exists order_items_product_id_idx on public.order_items(product_id);

-- Automatically create a customer profile when someone registers with Supabase Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Keep the item price tied to the current product price, rather than trusting a browser-supplied price.
create or replace function public.set_order_item_price()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_price numeric(12,2);
  active_product boolean;
begin
  select p.price, p.is_active
    into current_price, active_product
  from public.products p
  where p.id = new.product_id;

  if not found or not active_product or current_price is null then
    raise exception 'Product is unavailable for ordering';
  end if;

  new.unit_price := current_price;
  return new;
end;
$$;

drop trigger if exists set_order_item_price_before_write on public.order_items;
create trigger set_order_item_price_before_write
  before insert or update of product_id, quantity on public.order_items
  for each row execute procedure public.set_order_item_price();

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.profiles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.inventory enable row level security;
alter table public.breeding_batches enable row level security;

-- Storefront visitors can only view active categories and products.
drop policy if exists "Public can view active categories" on public.categories;
create policy "Public can view active categories"
  on public.categories for select
  using (is_active = true);

drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products"
  on public.products for select
  using (is_active = true);

-- Signed-in customers can view and update their own profile.
drop policy if exists "Customers can view own profile" on public.profiles;
create policy "Customers can view own profile"
  on public.profiles for select to authenticated
  using (auth.uid() = id);

drop policy if exists "Customers can update own profile" on public.profiles;
create policy "Customers can update own profile"
  on public.profiles for update to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- Customers can create orders for themselves and view their own orders.
drop policy if exists "Customers can view own orders" on public.orders;
create policy "Customers can view own orders"
  on public.orders for select to authenticated
  using (auth.uid() = customer_id);

drop policy if exists "Customers can create own orders" on public.orders;
create policy "Customers can create own orders"
  on public.orders for insert to authenticated
  with check (auth.uid() = customer_id and status = 'pending');

-- Customers can view their own order lines and add lines to their own pending orders.
drop policy if exists "Customers can view own order items" on public.order_items;
create policy "Customers can view own order items"
  on public.order_items for select to authenticated
  using (
    exists (
      select 1 from public.orders o
      where o.id = order_id and o.customer_id = auth.uid()
    )
  );

drop policy if exists "Customers can add items to own pending orders" on public.order_items;
create policy "Customers can add items to own pending orders"
  on public.order_items for insert to authenticated
  with check (
    exists (
      select 1 from public.orders o
      where o.id = order_id
        and o.customer_id = auth.uid()
        and o.status = 'pending'
    )
  );

